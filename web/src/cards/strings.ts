const DICTS: Record<string, Dict> = { hi, ta };

export type T = (key: StrKey, vars?: Record<string, string | number>) => string;

/** Localised label for an order or offer status ("in_production" → "In production"). */
export function statusLabel(status: string, t: T): string {
  const offer = ({ accepted: 'st_accepted', countered: 'st_countered', declined: 'st_declined', expired: 'st_expired' } as const)[status as 'accepted'];
  const key = (offer ?? `s_${status}`) as StrKey;
  const raw = t(key);
  return raw === key ? status.replace(/_/g, ' ') : raw;
}

/** Localised trust badge (the server sends English labels such as "GST verified", "12 repeat buyers"). */
export function badgeLabel(badge: string, t: T): string {
  const fixed: Record<string, StrKey> = {
    'GST verified': 'badge_gst',
    Manufacturer: 'badge_mfr',
    'Unit visited': 'badge_visited',
    'Replies in < 10 min': 'badge_fast',
    'Pays on time': 'badge_paysontime',
    'Top quality': 'badge_quality',
  };
  if (fixed[badge]) return t(fixed[badge]);
  const repeat = /^(\d+) repeat buyers$/.exec(badge);
  if (repeat) return t('badge_repeat', { n: repeat[1] });
  return badge;
}

export function strings(lang: string): T {
  const d = DICTS[lang] ?? {};
  return (key, vars) => {
    let s: string = d[key] ?? localeString(lang, 'cards', key) ?? en[key] ?? String(key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

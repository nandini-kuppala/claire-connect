export type CallStringKey = Parameters<ReturnType<typeof CallStrings.use>>[0];

/** m:ss (or h:mm:ss) with ASCII digits, the way every language in the app shows numbers. */
export function callDuration(sec: number): string {
  const s = Math.max(0, Math.round(sec));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${r}` : `${m}:${r}`;
}

/** One line for a CC:Call summary: "Voice call · 2:31", "Missed video call", "Call declined". */
export function callSummaryText(p: { media?: string; outcome?: string; durationSec?: number }, lang: string): string {
  const video = p.media === 'video';
  if (p.outcome === 'completed') return CallStrings.get(lang, video ? 'summary_video' : 'summary_voice', { time: callDuration(p.durationSec ?? 0) });
  if (p.outcome === 'declined') return CallStrings.get(lang, 'declined');
  return CallStrings.get(lang, video ? 'missed_video' : 'missed_voice');
}
